package Proxy;

public class Students
{
    private String sno;
    private String sname;

    public Students(String sno, String sname) {

        this.sno = sno;
        this.sname = sname;
    }
    public String getSno()
    {

        return sno;
    }

    public void setSno(String sno)
    {

        this.sno = sno;

    }
}
